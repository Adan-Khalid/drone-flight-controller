"""Check that KiCad's own netlist matches circuit.py pin by pin.

ERC proves the schematic has no electrical-rule problems, not that each label landed on the
intended pin. This exports the netlist with kicad-cli and compares every (part, pin) to the net
circuit.py gives it. Writes reports/hardware/netlist_check.md and exits non-zero on a mismatch.

Usage (from the repo root):
    uv run python hardware/gen/check_netlist.py
"""

from __future__ import annotations

import os
import subprocess
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import circuit  # noqa: E402
from build_schematic import resolve  # noqa: E402
from kicad_lib import pins  # noqa: E402
from sexp import find, find_all, parse  # noqa: E402

ROOT = HERE.parents[1]
SCH = ROOT / "hardware" / "kicad" / "dronefc.kicad_sch"
REPORT = ROOT / "reports" / "hardware" / "netlist_check.md"


def kicad_cli() -> str:
    exe = os.environ.get("KICAD_CLI")
    if exe:
        return exe
    win = Path(os.environ.get("LOCALAPPDATA", "")) / "Programs/KiCad/10.0/bin/kicad-cli.exe"
    return str(win) if win.exists() else "kicad-cli"


def export_netlist() -> dict[tuple[str, str], str]:
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "dronefc.net"
        subprocess.run([kicad_cli(), "sch", "export", "netlist", "--format", "kicadsexpr",
                        "-o", str(out), str(SCH)], check=True, capture_output=True)
        tree = parse(out.read_text(encoding="utf-8"))
    pin_net = {}
    for net in find_all(find(tree, "nets"), "net"):
        name = str(find(net, "name")[1]).rsplit("/", 1)[-1]
        for node in find_all(net, "node"):
            pin_net[(str(find(node, "ref")[1]), str(find(node, "pin")[1]))] = name
    return pin_net


def main() -> int:
    actual = export_netlist()
    expected = {}
    stacked = []
    unconnected = set()
    for part in circuit.PARTS:
        if part.lib.startswith("power:"):
            continue
        conn, nc = resolve(part)
        for pin, net in conn.items():
            expected[(part.ref, pin)] = net
        # hidden pins stacked under a connected pin share its net (extra SW and GND pads)
        ps = pins(part.lib)
        for h in (p for p in ps if p.hidden and p.number not in conn and p.number not in nc):
            for v in ps:
                if v.number in conn and (v.x, v.y) == (h.x, h.y):
                    expected[(part.ref, h.number)] = conn[v.number]
                    stacked.append(f"{part.ref}.{h.number}")
                    break
        unconnected |= {(part.ref, n) for n in nc}

    problems = []
    for key, net in sorted(expected.items()):
        got = actual.get(key)
        if got != net:
            problems.append(f"{key[0]} pin {key[1]}: expected {net}, KiCad has {got}")
    # pins KiCad puts on a real net although circuit.py leaves them unconnected
    for key in sorted(unconnected):
        got = actual.get(key)
        if got and not got.startswith("unconnected-"):
            problems.append(f"{key[0]} pin {key[1]}: expected no connection, KiCad has {got}")

    members = defaultdict(int)
    for net in expected.values():
        members[net] += 1
    single = sorted(n for n, c in members.items() if c == 1)

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Netlist check",
        "",
        "Generated by `hardware/gen/check_netlist.py`: KiCad's exported netlist compared with "
        "`hardware/gen/circuit.py`, pin by pin.",
        "",
        f"- Parts checked: {len({k[0] for k in expected})}",
        f"- Connected pins checked: {len(expected)}",
        f"- Unconnected pins checked: {len(unconnected)}",
        f"- Hidden stacked pins checked (included above): {', '.join(stacked)}",
        f"- Nets: {len(members)}",
        f"- Mismatches: {len(problems)}",
        "",
        "Nets with a single pin (expected only for test pads and jumpers): "
        + (", ".join(single) if single else "none"),
        "",
    ]
    if problems:
        lines += ["## Mismatches", ""] + [f"- {p}" for p in problems] + [""]
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
