"""Run ArduPilot's own board-file processor on this board's hwdef and check the DMA plan.

Fetches only the needed folders of ArduPilot at a pinned commit (about 5 MB) into .cache/,
copies firmware/hwdef/DroneFC-H743 into it, runs chibios_hwdef.py for the firmware and the
bootloader, and writes reports/firmware/hwdef_check.md. Fails if any peripheral is left
without DMA or if an IMU bus or motor timer shares its DMA stream with anything else.

Usage:
    uv run python scripts/check_hwdef.py
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from fcboard.hwdef_check import dma_assignments, exclusive, unresolved_line  # noqa: E402

ARDUPILOT_URL = "https://github.com/ArduPilot/ardupilot.git"
ARDUPILOT_COMMIT = "fe04abb61ecb80e1ac6893f56896690b91041f6f"  # master, 15 Nov 2026
BOARD = "DroneFC-H743"
LOCAL_TEST_ID = "AP_HW_DRONEFC_H743                    999 # LOCAL TEST ONLY, not allocated"
SPARSE = [
    "libraries/AP_HAL_ChibiOS/hwdef/scripts",
    "libraries/AP_HAL_ChibiOS/hwdef/common",
    "libraries/AP_HAL_ChibiOS/hwdef/include",
    "libraries/AP_HAL/hwdef/scripts",
    "Tools/AP_Bootloader",
]
CACHE = ROOT / ".cache" / "ardupilot"
OUT = ROOT / "reports" / "firmware"


def git(*args: str, cwd: Path) -> None:
    subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True)


def fetch_ardupilot() -> Path:
    head = CACHE / ".git" / "HEAD"
    if head.exists():
        rev = subprocess.run(["git", "rev-parse", "HEAD"], cwd=CACHE, capture_output=True,
                             text=True).stdout.strip()
        if rev == ARDUPILOT_COMMIT:
            return CACHE
        shutil.rmtree(CACHE)
    CACHE.mkdir(parents=True)
    git("init", "-q", cwd=CACHE)
    git("remote", "add", "origin", ARDUPILOT_URL, cwd=CACHE)
    git("sparse-checkout", "set", *SPARSE, cwd=CACHE)
    git("fetch", "-q", "--depth", "1", "--filter=blob:none", "origin", ARDUPILOT_COMMIT,
        cwd=CACHE)
    git("checkout", "-q", "FETCH_HEAD", cwd=CACHE)
    return CACHE


def prepare(ap: Path) -> Path:
    hwdef_dir = ap / "libraries" / "AP_HAL_ChibiOS" / "hwdef"
    dest = hwdef_dir / BOARD
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(ROOT / "firmware" / "hwdef" / BOARD, dest)
    board_types = ap / "Tools" / "AP_Bootloader" / "board_types.txt"
    text = board_types.read_text(encoding="utf-8")
    if "AP_HW_DRONEFC_H743" not in text:
        board_types.write_text(text.rstrip("\n") + "\n" + LOCAL_TEST_ID + "\n", encoding="utf-8")
    return hwdef_dir


def run_processor(hwdef_dir: Path, outdir: Path, bootloader: bool) -> str:
    outdir.mkdir(parents=True, exist_ok=True)
    board = hwdef_dir / BOARD
    cmd = [sys.executable, "chibios_hwdef.py", "-D", str(outdir)]
    if bootloader:
        cmd += ["--bootloader", str(board / "hwdef-bl.dat")]
    else:
        cmd += ["--params", str(board / "defaults.parm"), str(board / "hwdef.dat")]
    proc = subprocess.run(cmd, cwd=hwdef_dir / "scripts", capture_output=True, text=True)
    log = proc.stdout + proc.stderr
    if not (outdir / "hwdef.h").exists():
        raise SystemExit(f"chibios_hwdef.py produced no hwdef.h:\n{log[-2000:]}")
    return log


def main() -> int:
    ap = fetch_ardupilot()
    hwdef_dir = prepare(ap)
    work = ROOT / ".cache" / "hwdef_out"
    fw_log = run_processor(hwdef_dir, work / "firmware", bootloader=False)
    run_processor(hwdef_dir, work / "bootloader", bootloader=True)

    hwdef_h = (work / "firmware" / "hwdef.h").read_text(encoding="utf-8")
    unresolved = unresolved_line(hwdef_h)
    assigns = dma_assignments(hwdef_h)
    excl = exclusive(assigns, ("SPI1", "SPI4", "TIM2", "TIM3"))
    ok = unresolved is None and all(excl.values())

    OUT.mkdir(parents=True, exist_ok=True)
    lines = [
        "# ArduPilot board file check",
        "",
        f"Generated by `scripts/check_hwdef.py`: ArduPilot commit `{ARDUPILOT_COMMIT}`, "
        f"`chibios_hwdef.py` run on `firmware/hwdef/{BOARD}` (firmware and bootloader).",
        "",
        f"- Peripherals left without DMA: **{'none' if unresolved is None else unresolved}**",
        "- IMU buses and motor timers on their own streams: "
        f"**{'yes' if all(excl.values()) else 'no'}**",
        f"- Overall: **{'pass' if ok else 'FAIL'}**",
        "",
        "The firmware run ends by asking for a built bootloader binary, which needs the full "
        "build; that message is expected here and does not affect the pin or DMA check.",
        "",
        "| Peripheral | DMA | Stream | Shared with |",
        "| --- | --- | --- | --- |",
    ]
    for a in assigns:
        lines.append(f"| {a.peripheral} | {a.dma} | {a.stream} | {', '.join(a.shared_with)} |")
    (OUT / "hwdef_check.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (OUT / "hwdef_firmware_log.txt").write_text(fw_log, encoding="utf-8")
    print(f"wrote {(OUT / 'hwdef_check.md').relative_to(ROOT)}: {'pass' if ok else 'FAIL'}")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
